// Generates Styles.md: every TextMate rule and semantic token selector with its palette role and colors.

import * as fs from "fs";
import * as path from "path";
import { Config } from "../src/config";
import type { SyntaxColors } from "../src/theme";
import { generateTextMateTheme } from "../src/theme/textmate";
import { generateSemanticTheme, generateSemanticThemeColors } from "../src/theme/semantic";
import { darkSyntax } from "../src/dark";
import { blackContrastSyntax } from "../src/black-contrast";
import { lightSyntax } from "../src/light";

const config = Config.DEFAULT;
const themes: [string, SyntaxColors][] = [
  ["Dark", darkSyntax],
  ["High contrast", blackContrastSyntax],
  ["Light", lightSyntax],
];

type Style = { foreground?: string; fontStyle?: string };
// SemanticThemeColors keys that are spread into semanticTokenColors but aren't token types.
const notTokenTypes = new Set(["text", "faded", "mutVariable", "mutParameter", "mutFunction", "mutMethod", "error", "unsafe", "escapeSequence", "character"]);

// Palette names for a color, e.g. `pink`, several when palette entries share a value.
function roleOf(color: string | undefined): string {
  if (!color) return "";
  const names = Object.entries(darkSyntax)
    .filter(([, v]) => v.toUpperCase() === color.toUpperCase())
    .map(([k]) => k);
  return names.length ? names.join(" / ") : color;
}

const colors = (values: (string | undefined)[]) =>
  values.map((v) => (v ? `\`${v.toUpperCase()}\`` : "—")).join(" · ");

const textMate = themes.map(([, s]) => generateTextMateTheme(s, config).tokenColors as { name: string; scope: string | string[]; settings: Style }[]);
const semantic = themes.map(([, s]) => generateSemanticTheme(generateSemanticThemeColors(s, config), config));

const lines: string[] = [
  "# Styles",
  "",
  "<!-- Generated by `npm run buildStylesDoc` from the theme sources; don't edit by hand. -->",
  "",
  "Which colors the theme gives each TextMate scope and semantic token, with the default settings.",
  "Colors are listed as dark · high contrast · light. Roles are the palette names in `src/dark.ts`,",
  "`src/black-contrast.ts` and `src/light.ts`.",
  "",
  "Semantic tokens come from language servers (rust-analyzer, tsserver, Pylance, ...) and take precedence",
  "over TextMate scopes where a server provides them.",
  "",
  "## Semantic tokens",
  "",
  "Selectors are `type.modifier:language`; `*` matches any type.",
  "",
  "| Selector | Role | Colors | Style |",
  "|---|---|---|---|",
];
for (const [selector, value] of Object.entries(semantic[0]!)) {
  const style = (v: unknown): Style => (typeof v === "string" ? { foreground: v } : (v as Style));
  const s = style(value);
  if (!s.foreground && !s.fontStyle) continue;
  if (notTokenTypes.has(selector.split(/[.:]/)[0]!)) continue;
  const values = semantic.map((t) => style(t[selector]).foreground);
  lines.push(`| \`${selector}\` | ${roleOf(s.foreground)} | ${s.foreground ? colors(values) : ""} | ${s.fontStyle ?? ""} |`);
}

lines.push("", "## TextMate rules", "", "Later rules win over earlier ones when they match the same scope equally well.", "");
textMate[0]!.forEach((rule, i) => {
  const fg = rule.settings.foreground;
  const style = rule.settings.fontStyle;
  const scopes = Array.isArray(rule.scope) ? rule.scope : rule.scope.split(",").map((s) => s.trim());
  lines.push(`### ${rule.name}`, "");
  const parts = [];
  if (fg) parts.push(`${roleOf(fg)}: ${colors(textMate.map((t) => t[i]!.settings.foreground))}`);
  if (style) parts.push(`style: ${style}`);
  if (parts.length) lines.push(parts.join(", "), "");
  for (const scope of scopes) lines.push(`- \`${scope}\``);
  lines.push("");
});

const file = path.join(__dirname, "..", "Styles.md");
fs.writeFileSync(file, lines.join("\n"));
console.log(`Writing Styles.md to ${file}`);
